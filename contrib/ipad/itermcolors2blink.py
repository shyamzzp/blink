#!/usr/bin/env python3
"""Convert an iTerm2 .itermcolors file into a Blink (hterm) theme.

An .itermcolors file is a plist of "Ansi 0 Colour" through "Ansi 15 Colour"
plus Foreground, Background and Cursor, each stored as float RGB components
in 0..1. Blink themes are JavaScript executed against the live hterm
preference manager, so the conversion is a scale to 0..255 and a rewrite into
t.prefs_.set calls.

Usage:
    ./itermcolors2blink.py Solarized.itermcolors > solarized.js
    ./itermcolors2blink.py Solarized.itermcolors -o solarized.js

Host the result anywhere reachable by URL, then add it in Blink under
Settings > Terminal > Style > Themes.
"""

import argparse
import plistlib
import sys

# hterm's palette order is the standard ANSI order, which is also the order
# iTerm2 numbers its "Ansi N Colour" keys, so index maps straight across.
ANSI_NAMES = [
    "black", "red", "green", "yellow",
    "blue", "magenta", "cyan", "white",
    "lightBlack", "lightRed", "lightGreen", "lightYellow",
    "lightBlue", "lightMagenta", "lightCyan", "lightWhite",
]


def to_hex(entry):
    """One plist colour dict to #rrggbb."""
    def channel(key):
        value = float(entry.get(key, 0.0))
        return max(0, min(255, round(value * 255)))

    return "#{:02x}{:02x}{:02x}".format(
        channel("Red Component"),
        channel("Green Component"),
        channel("Blue Component"),
    )


def lookup(plist, *keys):
    for key in keys:
        if key in plist:
            return plist[key]
    return None


def convert(plist, name):
    palette = []
    for index in range(16):
        entry = lookup(plist, f"Ansi {index} Color", f"Ansi {index} Colour")
        if entry is None:
            raise SystemExit(f"missing 'Ansi {index} Color' in the input file")
        palette.append(to_hex(entry))

    foreground = lookup(plist, "Foreground Color", "Foreground Colour")
    background = lookup(plist, "Background Color", "Background Colour")
    cursor = lookup(plist, "Cursor Color", "Cursor Colour")

    out = []
    out.append(f"// {name}: converted from an iTerm2 .itermcolors file.")
    out.append("// Generated by contrib/ipad/itermcolors2blink.py")
    out.append("")
    for label, value in zip(ANSI_NAMES, palette):
        out.append(f"var {label:<13} = '{value}';")
    out.append("")
    out.append("t.prefs_.set('color-palette-overrides', [")
    for row in range(0, 16, 4):
        out.append("  " + ", ".join(ANSI_NAMES[row:row + 4]) + ("," if row < 12 else ""))
    out.append("]);")
    out.append("")
    if foreground is not None:
        out.append(f"t.prefs_.set('foreground-color', '{to_hex(foreground)}');")
    if background is not None:
        out.append(f"t.prefs_.set('background-color', '{to_hex(background)}');")
    if cursor is not None:
        out.append(f"t.prefs_.set('cursor-color', '{to_hex(cursor)}');")
    out.append("")
    out.append("// Behaviour parity with a typical iTerm2 setup. Trim to taste.")
    out.append("t.prefs_.set('copy-on-select', true);")
    out.append("t.prefs_.set('clear-selection-after-copy', true);")
    out.append("t.prefs_.set('enable-bold-as-bright', true);")
    out.append("t.prefs_.set('hide-mouse-while-typing', true);")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("input", help="path to a .itermcolors file")
    parser.add_argument("-o", "--output", help="write here instead of stdout")
    parser.add_argument("-n", "--name", help="theme name for the header comment")
    args = parser.parse_args()

    with open(args.input, "rb") as handle:
        plist = plistlib.load(handle)

    name = args.name or args.input.rsplit("/", 1)[-1].rsplit(".", 1)[0]
    result = convert(plist, name)

    if args.output:
        with open(args.output, "w") as handle:
            handle.write(result)
    else:
        sys.stdout.write(result)


if __name__ == "__main__":
    main()
